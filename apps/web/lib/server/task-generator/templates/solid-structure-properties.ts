import type { DistractorRule, Params, TaskBlueprint } from "../types.ts";

const prompts = [
  "Шар изготовлен из монокристалла, тепловое расширение которого зависит от направления. Что может произойти при равномерном нагревании?",
  "Стальной образец состоит из множества беспорядочно ориентированных маленьких кристаллов. Как обычно проявляются его свойства в разных направлениях?",
  "При постоянном давлении кристаллическое тело нагревают и плавят. Как ведёт себя температура во время плавления?",
  "Аморфное тело медленно нагревают. Как оно переходит в жидкое состояние?",
] as const;

const optionLabels: Record<number, readonly string[]> = {
  1: [
    "Может измениться и объём, и форма",
    "Изменится только объём, форма обязательно сохранится",
    "Объём обязательно уменьшится",
    "Никаких изменений не произойдёт",
  ],
  2: [
    "Обычно одинаково: направления отдельных зёрен усредняются",
    "Всегда как у одного монокристалла",
    "Только вдоль самого крупного зерна",
    "Свойства определяются формой образца, а не строением",
  ],
  3: [
    "Остаётся постоянной до завершения плавления",
    "Непрерывно растёт с прежней скоростью",
    "Сразу падает до комнатной",
    "Становится равной абсолютному нулю",
  ],
  4: [
    "Постепенно размягчается в некотором интервале температур",
    "Плавится строго при одной температуре с горизонтальным участком",
    "Сразу превращается в газ",
    "Не может перейти в жидкое состояние",
  ],
};

function answerFor(): number {
  return 1;
}

function shiftedAnswer(offset: number): DistractorRule {
  return {
    label: `выбран неверный вывод о строении твёрдого тела ${offset}`,
    compute: () => offset + 1,
  };
}

function explanation(params: Params): string {
  if (params.caseId === 1) return "Монокристалл анизотропен: коэффициент теплового расширения может различаться по направлениям, поэтому шар способен изменить не только объём, но и форму.";
  if (params.caseId === 2) return "Поликристалл состоит из множества беспорядочно ориентированных зёрен. Их направления усредняются, поэтому в обычной школьной модели материал изотропен.";
  if (params.caseId === 3) return "У кристаллического тела при постоянном давлении есть определённая температура плавления. Подводимая теплота во время фазового перехода не повышает температуру.";
  return "У аморфного тела нет определённой температуры плавления: при нагревании оно постепенно размягчается и переходит в жидкое состояние.";
}

export const solidStructurePropertiesBlueprint: TaskBlueprint = {
  id: "solid-structure-properties",
  skill: "Строение и свойства твёрдых тел",
  topic: "Термодинамика",
  group: "thermodynamics",
  difficulty: 1,
  params: { caseId: { min: 1, max: 4, step: 1, unit: "сценарий" } },
  formula: "\\text{строение}\\;\\Longrightarrow\\;\\text{наблюдаемое свойство}",
  answerUnit: "",
  answerKind: "positive",
  solver: answerFor,
  distractors: [shiftedAnswer(1), shiftedAnswer(2), shiftedAnswer(3)],
  optionText: (value, params) => optionLabels[params.caseId]?.[value - 1] ?? String(value),
  textTemplate: params => prompts[params.caseId - 1] ?? prompts[0],
  explanationTemplate: params => explanation(params),
  trap: "Сначала определи строение образца: один кристалл, множество зёрен или аморфное тело. Затем связывай его с наблюдаемым свойством.",
  coachLines: {
    correct: params => `Верно. ${explanation(params)}`,
    wrong: params => `Не ориентируйся только на внешний вид образца. ${explanation(params)}`,
  },
};
