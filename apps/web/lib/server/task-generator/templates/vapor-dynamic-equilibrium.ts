function answerFor(): number {
  return 1;
}

function shiftedAnswer(offset: number): DistractorRule {
  return { label: `выбран неверный вывод о паре ${offset}`, compute: () => offset + 1 };
}

function explanation(params: Params): string {
  if (params.caseId === 1) return "Динамическое равновесие означает равенство встречных потоков, а не прекращение молекулярного движения.";
  if (params.caseId === 2) return "Поверхность покидают более быстрые молекулы; средняя кинетическая энергия оставшихся уменьшается, поэтому жидкость охлаждается.";
  if (params.caseId === 3) return "При той же температуре равновесное давление насыщенного пара восстанавливается за счёт конденсации части пара.";
  return "После ухода части пара его концентрация уменьшается, конденсация ослабевает и испарение временно преобладает.";
}

