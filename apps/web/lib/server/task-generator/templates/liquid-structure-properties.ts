import type { DistractorRule, Params, TaskBlueprint } from "../types.ts";

const prompts = [
  "Жидкость перелили из широкого сосуда в узкий, не пролив её. Что сохранилось и что изменилось?",
  "Молекула жидкости некоторое время колеблется около временного положения равновесия, затем переходит к соседнему. Какое свойство это объясняет?",
  "Почему результирующая сил притяжения для молекулы в поверхностном слое обычно направлена внутрь жидкости?",
  "Две небольшие капли воды соприкоснулись и слились в одну. Какой общий вывод согласуется с поверхностным натяжением?",
] as const;

